#!/bin/sh
set -eu

VERSION_FILE=${1:-VERSION}
OUTPUT_FILE=${2:-libmapi/version.h}
PACKAGE_VERSION=${3:?package version is required}
SOURCE_DIR=${4:-.}

OPENCHANGE_MAJOR_RELEASE=${PACKAGE_VERSION%%.*}
OPENCHANGE_MINOR_RELEASE=${PACKAGE_VERSION#*.}
OPENCHANGE_MINOR_RELEASE=${OPENCHANGE_MINOR_RELEASE%%.*}

VERSION_PATH=$SOURCE_DIR/$VERSION_FILE
SNAPSHOT=$(sed -n 's/^OPENCHANGE_VERSION_IS_GIT_SNAPSHOT=//p' "$VERSION_PATH")
NICKNAME=$(sed -n 's/^OPENCHANGE_VERSION_RELEASE_NICKNAME=//p' "$VERSION_PATH")
RELEASE_NUMBER=$(sed -n 's/^OPENCHANGE_VERSION_RELEASE_NUMBER=//p' "$VERSION_PATH")
GIT_INFO=

# A source archive inside another checkout must not inherit the parent's revision.
if [ "$SNAPSHOT" = yes ] && [ -e "$SOURCE_DIR/.git" ]; then
    GIT_INFO=$(git -C "$SOURCE_DIR" rev-parse --short HEAD 2>/dev/null || :)
fi

BASE_VERSION=$PACKAGE_VERSION
if [ -n "$GIT_INFO" ]; then
    BASE_VERSION=$PACKAGE_VERSION-GIT-build-$GIT_INFO
fi
OFFICIAL_VERSION=${RELEASE_NUMBER:-$BASE_VERSION}
DISPLAY_VERSION=$OFFICIAL_VERSION
if [ -n "$NICKNAME" ]; then
    if [ -n "$GIT_INFO" ]; then
        DISPLAY_VERSION="$DISPLAY_VERSION-GIT-$GIT_INFO"
    fi
    DISPLAY_VERSION="$DISPLAY_VERSION ($NICKNAME)"
fi

c_string() {
    printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'
}

TASK_TMP=$(mktemp "$OUTPUT_FILE.tmp.XXXXXX")
trap 'rm -f "$TASK_TMP"' EXIT
trap 'exit 1' HUP INT TERM
{
    printf '/* Autogenerated by script/mkversion.sh */\n'
    printf '#define OPENCHANGE_MAJOR_RELEASE %s\n' "$OPENCHANGE_MAJOR_RELEASE"
    printf '#define OPENCHANGE_MINOR_RELEASE %s\n' "$OPENCHANGE_MINOR_RELEASE"
    if [ -n "$GIT_INFO" ]; then
        printf '#define OPENCHANGE_VERSION_GIT_REVISION "%s"\n' "$GIT_INFO"
    fi
    printf '#define OPENCHANGE_VERSION_OFFICIAL_STRING "%s"\n' "$(c_string "$OFFICIAL_VERSION")"
    if [ -n "$NICKNAME" ]; then
        printf '#define OPENCHANGE_VERSION_RELEASE_NICKNAME "%s"\n' "$(c_string "$NICKNAME")"
    fi
    printf '#define OPENCHANGE_VERSION_STRING "%s"\n' "$(c_string "$DISPLAY_VERSION")"
} > "$TASK_TMP"

if [ ! -f "$OUTPUT_FILE" ] || ! cmp -s "$TASK_TMP" "$OUTPUT_FILE"; then
    mv "$TASK_TMP" "$OUTPUT_FILE"
    printf '%s: %s created for OpenChange libmapi("%s")\n' "$0" "$OUTPUT_FILE" "$DISPLAY_VERSION"
fi
